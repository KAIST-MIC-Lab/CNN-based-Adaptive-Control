function vehicl_params = vehicle_params()
    vehicl_params.m = 1500; % kg
    vehicl_params.l1 = 2.5; % m
    vehicl_params.l2 = 1.60; % m
    vehicl_params.C1 = 90000; % N/rad
    vehicl_params.C2 = 90000; % N/rad
    vehicl_params.Fmax = 8000; % N
    vehicl_params.Iz = 2250; % kg*m^2
    vehicl_params.vx = 5; % m/s (constant longitudinal velocity)                                             
end

